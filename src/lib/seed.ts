// Tanggal dibuat relatif terhadap hari ini supaya demo selalu terasa hidup.
function hariLalu(n: number): string {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return d.toISOString().slice(0, 10);
}
function hariDepan(n: number): string {
  const d = new Date();
  d.setDate(d.getDate() + n);
  return d.toISOString().slice(0, 10);
}

